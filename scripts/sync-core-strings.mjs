#!/usr/bin/env node
/**
 * Vendor astrid-core's shared strings and write them into web's locale files (AWTD-1649).
 *
 *   node scripts/sync-core-strings.mjs                 # re-apply the vendored revision
 *   node scripts/sync-core-strings.mjs --rev <sha>     # move the pin: re-vendor, then apply
 *   node scripts/sync-core-strings.mjs --core <dir>    # read core from here (default ../astrid-core)
 *
 * Vendors into lib/i18n/core-strings/: REVISION, sources.json (each shared key's web keys) and
 * web/<locale>.json (core's `cargo xtask gen-strings` output, committed in core). Read with
 * `git show <rev>:…`, so it needs git and a core checkout, not Rust.
 *
 * Then, for every web key core's map names, writes core's value into lib/i18n/locales/<locale>.json
 * under web's own key name, so call sites do not change — except the pairs on
 * lib/i18n/core-strings/divergent.json, which keep web's wording until someone decides which
 * translation wins. `--update-divergent` rewrites that list from the current files (it may
 * only shrink; the ratchet test refuses a new entry). The rules live in
 * scripts/lib/core-strings.mjs, which the test shares.
 */
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { divergenceIds, setPath, sharedStringPlan } from './lib/core-strings.mjs'

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const vendored = join(web, 'lib', 'i18n', 'core-strings')
const localesDir = join(web, 'lib', 'i18n', 'locales')
const LOCALES = ['en', 'es', 'fr', 'de', 'it', 'pt', 'ja', 'ko', 'zh-CN', 'zh-TW', 'nl', 'ru']

const args = process.argv.slice(2)
const flag = name => {
  const i = args.indexOf(name)
  return i >= 0 ? args[i + 1] : undefined
}
const core = resolve(flag('--core') ?? join(web, '..', 'astrid-core'))
const rev = flag('--rev')

const readJson = path => JSON.parse(readFileSync(path, 'utf8'))
const writeJson = (path, value) => writeFileSync(path, `${JSON.stringify(value, null, 2)}\n`)

if (rev) {
  const sha = execFileSync('git', ['-C', core, 'rev-parse', `${rev}^{commit}`], { encoding: 'utf8' }).trim()
  const show = path => execFileSync('git', ['-C', core, 'show', `${sha}:${path}`], { encoding: 'utf8', maxBuffer: 64 << 20 })
  mkdirSync(join(vendored, 'web'), { recursive: true })
  writeFileSync(join(vendored, 'REVISION'), `${sha}\n`)
  writeFileSync(join(vendored, 'sources.json'), show('strings/shared/sources.json'))
  for (const locale of LOCALES) {
    writeFileSync(join(vendored, 'web', `${locale}.json`), show(`strings/generated/web/${locale}.json`))
  }
  console.log(`vendored astrid-core ${sha.slice(0, 7)} into lib/i18n/core-strings/`)
}

const divergentPath = join(vendored, 'divergent.json')
const webLocales = Object.fromEntries(LOCALES.map(l => [l, readJson(join(localesDir, `${l}.json`))]))
const plan = sharedStringPlan({
  sources: readJson(join(vendored, 'sources.json')),
  core: Object.fromEntries(LOCALES.map(l => [l, readJson(join(vendored, 'web', `${l}.json`))])),
  web: webLocales,
})

// A pair on the divergence list keeps web's wording until someone settles it. Any other pair that
// differs is one core changed since the last pin, so web takes core's value.
const updating = args.includes('--update-divergent')
if (!updating && !existsSync(divergentPath)) {
  console.error('lib/i18n/core-strings/divergent.json is missing: run with --update-divergent first, so web keeps its wording until each pair is settled')
  process.exit(1)
}
const allowed = new Set(updating ? [] : readJson(divergentPath).pairs)
const writes = updating ? [] : plan.pairs.filter(p => p.status === 'differ' && !allowed.has(`${p.locale} ${p.webKey}`))
if (!updating) {
  for (const w of writes) setPath(webLocales[w.locale], w.webKey, w.core)
  for (const locale of new Set(writes.map(w => w.locale))) writeJson(join(localesDir, `${locale}.json`), webLocales[locale])
}

const after = sharedStringPlan({
  sources: readJson(join(vendored, 'sources.json')),
  core: Object.fromEntries(LOCALES.map(l => [l, readJson(join(vendored, 'web', `${l}.json`))])),
  web: webLocales,
})
const divergent = divergenceIds(after.pairs)
if (updating) {
  writeJson(divergentPath, {
    note: 'GENERATED by scripts/sync-core-strings.mjs --update-divergent. Web keys (per locale) whose wording differs from astrid-core\'s shared catalog, or that two shared keys claim with different values. Each keeps web\'s wording until settled; the list may only shrink (tests/i18n/core-shared-strings-awtd-1649.test.ts).',
    pairs: divergent,
  })
}

const count = status => after.pairs.filter(p => p.status === status).length
console.log(`${after.mapped.length} web keys mapped; ${after.pairs.length} locale pairs: ${count('agree')} agree, ${count('differ')} differ, ${count('conflict')} conflict; ${writes.length} values taken from core`)
const reasons = {}
for (const s of after.skipped) reasons[s.reason] = (reasons[s.reason] ?? 0) + 1
if (after.skipped.length) console.log(`skipped ${after.skipped.length}:`, reasons)
