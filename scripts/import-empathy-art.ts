#!/usr/bin/env npx tsx
/**
 * Import the high-fidelity empathy-state frames from astrid-ios (ADEV-142, for iOS ADEV-127).
 *
 *   npx tsx scripts/import-empathy-art.ts [path-to-astrid-ios]   # default ../astrid-ios
 *
 * The art is drawn and committed in astrid-ios, at
 * docs/design/empathy-states/hifi/webp/<metaphor>-<state>.webp. It is read from that repo's
 * `origin/main` with `git show`, not from its working tree, so a half-finished render on a
 * local branch can't be published.
 *
 * Each frame is written to public/images/empathy-art/<metaphor>-<state>.<sha256[0:12]>.webp, so
 * its URL changes whenever its bytes do and can be cached forever. lib/empathy-art/frames.json
 * records each frame's file, sha256 and size; GET /api/v1/empathy-art serves that as the
 * manifest. Files from an earlier set are deleted.
 *
 * Re-run it whenever the art changes in astrid-ios, then commit both directories.
 */
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { EMPATHY_METAPHORS, EMPATHY_STATES } from '../lib/empathy-art/rules'

const ROOT = resolve(__dirname, '..')
const iosRoot = resolve(process.argv[2] ?? join(ROOT, '../astrid-ios'))
const SOURCE_DIR = 'docs/design/empathy-states/hifi/webp'
const OUT_DIR = join(ROOT, 'public/images/empathy-art')
const FRAMES_JSON = join(ROOT, 'lib/empathy-art/frames.json')

execFileSync('git', ['-C', iosRoot, 'fetch', '--quiet', 'origin', 'main'], { stdio: 'inherit' })

mkdirSync(OUT_DIR, { recursive: true })
for (const stale of readdirSync(OUT_DIR)) rmSync(join(OUT_DIR, stale))

const frames = []
for (const metaphor of EMPATHY_METAPHORS) {
  for (const state of EMPATHY_STATES) {
    const bytes = execFileSync('git', ['-C', iosRoot, 'show', `origin/main:${SOURCE_DIR}/${metaphor}-${state}.webp`], {
      maxBuffer: 16 * 1024 * 1024,
    })
    const sha256 = createHash('sha256').update(bytes).digest('hex')
    const file = `${metaphor}-${state}.${sha256.slice(0, 12)}.webp`
    writeFileSync(join(OUT_DIR, file), bytes)
    frames.push({ metaphor, state, file, sha256, bytes: bytes.length })
  }
}

const source = execFileSync('git', ['-C', iosRoot, 'rev-parse', 'origin/main'], { encoding: 'utf8' }).trim()
writeFileSync(
  FRAMES_JSON,
  `${JSON.stringify({ $comment: 'Generated by scripts/import-empathy-art.ts. Do not edit.', source: `astrid-ios@${source}`, frames }, null, 2)}\n`,
)
console.log(`Imported ${frames.length} frames from astrid-ios@${source.slice(0, 8)}`)
